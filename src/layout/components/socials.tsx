export const PLATFORM_ALIAS: Record<string, string> = {
  telegram: 'telegram',
  whatsapp: 'whatsapp',
  instagram: 'instagram',
  twitter: 'twitter',
  x: 'x',
  facebook: 'facebook',
  youtube: 'youtube',
  baleh: 'baleh',
  eeta: 'eeta',
  digikala: 'digikala',
  torob: 'torob',
  rubika: 'rubika',
  globalAddress: 'globalAddress'
};

export interface SocialLink {
  platform: string;
  url: string;
  label?: string;
}

interface SocialsProps {
  links?: SocialLink[];
}

export default function Socials({ links }: SocialsProps) {
  const shouldFetch = !links;
  const { data } = useSiteInfo({ skip: !shouldFetch });

  const socialLinks = useMemo(() => {
    const source = links ?? data?.socials ?? [];
    return source.filter((item) => item.url && item.platform);
  }, [links, data?.socials]);

  if (!socialLinks.length) {
    return null;
  }

  const globalAddress = socialLinks.find(x => x.platform === PLATFORM_ALIAS.globalAddress);

  return (
    <Stack gap={2}>
      {!!globalAddress && <Typography variant='caption'>
        آدرس ما در تمامی پیام رسان ها: <span style={{ direction: 'ltr', display: 'inline-block' }}>
          {globalAddress.url}
        </span>
      </Typography>}
      <Stack direction="row" alignItems="center" sx={{ mb: 2 }}>
        {socialLinks.filter(x => x.platform !== PLATFORM_ALIAS.globalAddress).map((social) => {
          const key = PlatformKey(social.platform);
          const icon = ICONS[key];
          return (
            <IconButton
              key={`${social.platform}-${social.url}`}
              component={Link}
              href={social.url}
              target="_blank"
              rel="noopener noreferrer"
              aria-label={social.platform}
            >
              {icon ?? ICONS.instagram}
            </IconButton>
          );
        })}
      </Stack>
    </Stack>
  );
}

export function PlatformKey(platform: string): string {
  const normalized = platform.trim().toLowerCase();
  return PLATFORM_ALIAS[normalized] ?? normalized;
}
